# Day 3 - Conditions (if/else)
# Python Backend Journey

age = 18
marks = 75

print(f"My Age: {age}")

# 1. if-else check
if age >= 18:
    print("You are Adult")
else:
    print("You are Minor")

# 2. elif check
if marks >= 90:
    print("Grade: A")
elif marks >= 75:
    print("Grade: B")
elif marks >= 50:
    print("Grade: C")
else:
    print("Grade: Fail")

print("Day 3 Completed!")
